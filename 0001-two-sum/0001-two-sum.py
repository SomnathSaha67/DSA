class Solution(object):
    def twoSum(self, nums, target):
        """
        :type nums: List[int]
        :type target: int
        :rtype: List[int]
        """
        lookup= {}

        for i, num in enumerate(nums):

            comp= target-num

            if comp in lookup: return [lookup[comp], i]
            else: lookup[num]= i
        return [-1, -1]

