class Solution(object):
    def numJewelsInStones(self, jewels, stones):
        """
        :type jewels: str
        :type stones: str
        :rtype: int
        """
        c=0
        for char in jewels:
            for mar in stones:
                if char==mar:
                    c+=1
        return c

